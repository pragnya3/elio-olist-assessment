USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS ELIO_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS OLIST;
CREATE SCHEMA IF NOT EXISTS OLIST.RAW;
CREATE SCHEMA IF NOT EXISTS OLIST.STAGING;
CREATE SCHEMA IF NOT EXISTS OLIST.MARTS;

USE WAREHOUSE ELIO_WH;
USE SCHEMA OLIST.RAW;

CREATE OR REPLACE FILE FORMAT OLIST.RAW.CSV_FF
  TYPE = 'CSV'
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  ENCODING = 'UTF8'
  NULL_IF = ('', 'NULL')
  EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE OLIST.RAW.OLIST_STAGE
  FILE_FORMAT = OLIST.RAW.CSV_FF;